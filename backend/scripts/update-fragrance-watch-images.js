// ─── Rebuild catalog ──────────────────────────────────────────────────────────
// Strip UTF-8 BOM if present (PowerShell sometimes writes it)
let rawJson = fs.readFileSync(CATALOG_PATH, "utf8");
if (rawJson.charCodeAt(0) === 0xFEFF) rawJson = rawJson.slice(1);
const existing = JSON.parse(rawJson);

// Keep everything that is NOT Fragrances or Watches
const otherProducts = existing.filter(
  (p) => p.category !== "Fragrances" && p.category !== "Watches"
);

const updated = [...otherProducts, ...fragrances, ...watches];

fs.writeFileSync(CATALOG_PATH, JSON.stringify(updated, null, 2), "utf8");

